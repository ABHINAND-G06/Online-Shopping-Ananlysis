"""Create a SYNTHETIC online-retail transaction file for demonstration only.

The data is generated by a random process with a few deliberately planted
product bundles (for example tea set items). It does NOT describe real
customers. Its purpose is to let the pipeline run end-to-end when the public
UCI Online Retail dataset is not available. A fixed random seed makes the file
reproducible.

The file also contains typical data-quality problems (cancelled invoices,
negative quantities, zero prices, missing descriptions, non-product service
codes and repeated lines) so that the cleaning step has something to do.
"""
import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from .config import DEFAULT_DATASET

# (stock code, description, unit price)
CATALOGUE = [
    ("P001", "Ceramic Teapot", 12.50), ("P002", "Tea Cup Set", 9.95),
    ("P003", "Tea Saucer Set", 7.50), ("P004", "Sugar Bowl", 4.25),
    ("P005", "Scented Candle", 3.95), ("P006", "Candle Holder", 5.50),
    ("P007", "Matches Box", 0.85), ("P008", "Gift Wrap Roll", 2.10),
    ("P009", "Gift Tag Pack", 1.25), ("P010", "Satin Ribbon", 1.65),
    ("P011", "Greeting Card", 1.95), ("P012", "Notebook A5", 3.50),
    ("P013", "Gel Pen Pack", 2.75), ("P014", "Highlighter Set", 3.10),
    ("P015", "Desk Organiser", 8.95), ("P016", "Lunch Box", 6.25),
    ("P017", "Water Bottle", 5.95), ("P018", "Insulated Bag", 7.40),
    ("P019", "Phone Case", 6.50), ("P020", "USB Charger", 8.20),
    ("P021", "Charging Cable", 4.60), ("P022", "Screen Protector", 3.30),
    ("P023", "Photo Frame", 7.95), ("P024", "Wall Clock", 14.50),
    ("P025", "Cushion Cover", 6.80), ("P026", "Throw Blanket", 16.90),
    ("P027", "Storage Basket", 9.50), ("P028", "Coat Hanger Set", 4.75),
    ("P029", "Kitchen Towel Set", 5.25), ("P030", "Oven Glove", 4.45),
    ("P031", "Mixing Bowl", 8.05), ("P032", "Wooden Spoon Set", 3.65),
    ("P033", "Bookmark Set", 1.15), ("P034", "Jigsaw Puzzle", 11.90),
    ("P035", "Playing Cards", 2.55), ("P036", "Plant Pot", 5.10),
    ("P037", "Garden Gloves", 3.85), ("P038", "Seed Packet", 1.45),
    ("P039", "Key Ring", 1.35), ("P040", "Tote Bag", 4.15),
]
NAME_TO_ROW = {name: (code, price) for code, name, price in CATALOGUE}

# Planted bundles: (items, probability that a basket starts from this bundle)
BUNDLES = [
    (["Ceramic Teapot", "Tea Cup Set", "Tea Saucer Set", "Sugar Bowl"], 0.060),
    (["Scented Candle", "Candle Holder", "Matches Box"], 0.055),
    (["Gift Wrap Roll", "Gift Tag Pack", "Satin Ribbon", "Greeting Card"], 0.070),
    (["Notebook A5", "Gel Pen Pack", "Highlighter Set"], 0.060),
    (["Phone Case", "Screen Protector", "Charging Cable", "USB Charger"], 0.055),
    (["Lunch Box", "Water Bottle", "Insulated Bag"], 0.050),
    (["Plant Pot", "Garden Gloves", "Seed Packet"], 0.040),
    (["Mixing Bowl", "Wooden Spoon Set", "Oven Glove"], 0.040),
    (["Cushion Cover", "Throw Blanket"], 0.035),
]
ITEM_KEEP_PROB = 0.85       # each bundle item is added with this probability
SERVICE_CODES = [("POST", "Postage"), ("DOT", "Dotcom Postage"), ("M", "Manual")]


def build_dataset(n_invoices: int = 4000, seed: int = 42) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    names = [row[1] for row in CATALOGUE]
    # Filler items follow a skewed popularity distribution (few popular, many rare)
    popularity = 1.0 / np.arange(1, len(names) + 1) ** 0.8
    popularity = rng.permutation(popularity)
    popularity /= popularity.sum()

    bundle_probs = np.array([b[1] for b in BUNDLES])
    start = pd.Timestamp("2025-01-01 08:00")
    rows = []
    for i in range(n_invoices):
        invoice = f"{500000 + i}"
        basket = set()
        # Each bundle is chosen independently, so a basket may hold several
        for (items, _), p in zip(BUNDLES, bundle_probs):
            if rng.random() < p:
                basket.update(it for it in items if rng.random() < ITEM_KEEP_PROB)
        # Filler items
        n_filler = rng.choice([0, 1, 2, 3, 4], p=[0.30, 0.30, 0.20, 0.12, 0.08])
        if n_filler:
            basket.update(rng.choice(names, size=n_filler, replace=False, p=popularity))
        if not basket:
            basket.add(str(rng.choice(names, p=popularity)))

        when = start + pd.Timedelta(minutes=int(rng.integers(0, 60 * 24 * 364)))
        customer = int(rng.integers(12000, 12900)) if rng.random() > 0.08 else np.nan
        cancelled = rng.random() < 0.03
        for name in sorted(basket):
            code, price = NAME_TO_ROW[name]
            qty = int(rng.choice([1, 2, 3, 4, 6], p=[0.50, 0.25, 0.10, 0.10, 0.05]))
            rows.append([("C" + invoice) if cancelled else invoice, code, name,
                         -qty if cancelled else qty, when, price, customer])
            # Occasionally the same product appears on two lines of one invoice
            if not cancelled and rng.random() < 0.03:
                rows.append([invoice, code, name, 1, when, price, customer])
        # Occasional service (non-product) line
        if rng.random() < 0.10:
            code, desc = SERVICE_CODES[int(rng.integers(0, len(SERVICE_CODES)))]
            rows.append([invoice, code, desc, 1, when, 15.0, customer])

    df = pd.DataFrame(rows, columns=["InvoiceNo", "StockCode", "Description",
                                     "Quantity", "InvoiceDate", "UnitPrice", "CustomerID"])
    # Inject a small number of other quality problems
    idx = rng.choice(df.index, size=40, replace=False)
    df.loc[idx[:25], "Description"] = np.nan          # missing description
    df.loc[idx[25:], "UnitPrice"] = 0.0               # invalid price
    df["InvoiceDate"] = df["InvoiceDate"].dt.strftime("%Y-%m-%d %H:%M")
    return df


def main():
    parser = argparse.ArgumentParser(description="Generate the synthetic demo dataset.")
    parser.add_argument("--out", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--invoices", type=int, default=4000)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    df = build_dataset(args.invoices, args.seed)
    df.to_csv(args.out, index=False)
    print(f"SYNTHETIC dataset written to {args.out} ({len(df)} rows, "
          f"{df['InvoiceNo'].nunique()} invoices)")


if __name__ == "__main__":
    main()
